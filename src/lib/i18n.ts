const DICT: Record<Lang, Dict> = { en, ar };

/** Translate a key for `lang`, interpolating {vars}. Falls back to English. */
export function translate(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>
): string {
  let out = DICT[lang][key] ?? DICT.en[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.replaceAll(`{${name}}`, String(value));
    }
  }
  return out;
}

/** Localized date formatting (Gregorian, locale-aware). */
export function formatDate(value: string | Date, lang: Lang): string {
  const date = typeof value === "string" ? new Date(value) : value;
  if (Number.isNaN(date.getTime())) return "";
  return date.toLocaleDateString(lang === "ar" ? "ar" : "en", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });
}
